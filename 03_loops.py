# --- 1. FOR LOOP (Counting & Repetition) ---
print("--- For Loop Demo ---")
print("Countdown starting for Game Launch:")

# range(1, 6) ka matlab hai 1 se shuru karke 5 tak chalna (end value se 1 kam)
for i in range(1, 6):
    print(f"Counting: {i}")

print("🚀 Game Started!\n")


# --- 2. WHILE LOOP (Game Loop Logic) ---
print("--- While Loop Demo ---")

player_health = 100
hit_count = 0

# Jab tak player ki health 0 se badi hai, loop chalega
while player_health > 0:
    hit_count += 1
    player_health -= 30  # Har baar Enemy 30 damage deta hai
    print(f"Hit {hit_count}: Enemy attacked! Health left: {player_health}")

print("💀 Player Defeated! GAME OVER!")# ===================================================
